function numbers100To200(speed) {

    if (speed < 100) {

        console.log('Less than 100');

    } else if (speed >= 100 && speed <= 200) {

        console.log('Between 100 and 200');

    } else {

        console.log('Greater than 200');

    }
}
numbers100To200(95);
numbers100To200(120);
numbers100To200(210);